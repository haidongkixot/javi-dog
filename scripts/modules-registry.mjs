// Builds docs/modules/REGISTRY.md from every module.json plus docs/modules/planned.json (ADR-0001).
// Usage: node scripts/modules-registry.mjs [--check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = join(root, 'docs/modules/REGISTRY.md');
const ID = /^JD-(APP|M\d{2}|C\d{2})$/;
const REQUIRED = ['id', 'name', 'version', 'status', 'description', 'provides', 'consumes'];
const STATUSES = new Set(['planned', 'in-progress', 'stable', 'deprecated']);

const errors = [];
const modules = [];

for (const dir of ['apps', 'packages', 'collectors']) {
  const base = join(root, dir);
  if (!existsSync(base)) continue;
  for (const entry of readdirSync(base, { withFileTypes: true })) {
    const file = join(base, entry.name, 'module.json');
    if (!entry.isDirectory() || !existsSync(file)) continue;
    const m = JSON.parse(readFileSync(file, 'utf8'));
    const path = `${dir}/${entry.name}`;
    for (const key of REQUIRED)
      if (!(key in m)) errors.push(`${path}/module.json: missing "${key}"`);
    if (!ID.test(m.id)) errors.push(`${path}/module.json: invalid id "${m.id}"`);
    if (!STATUSES.has(m.status)) errors.push(`${path}/module.json: invalid status "${m.status}"`);
    modules.push({ ...m, path, sprint: '—' });
  }
}

const planned = JSON.parse(readFileSync(join(root, 'docs/modules/planned.json'), 'utf8'));
for (const p of planned) {
  if (modules.some((m) => m.id === p.id)) {
    errors.push(`${p.id} exists as a package; remove it from docs/modules/planned.json`);
    continue;
  }
  modules.push({ ...p, version: '—', provides: [], consumes: [] });
}

const seen = new Map();
for (const m of modules) {
  if (seen.has(m.id)) errors.push(`duplicate id ${m.id} (${seen.get(m.id)} and ${m.path})`);
  seen.set(m.id, m.path);
}
for (const m of modules) {
  for (const dep of m.consumes ?? []) {
    if (!seen.has(dep)) errors.push(`${m.id} consumes unknown module ${dep}`);
  }
}

if (errors.length) {
  console.error(errors.map((e) => `✗ ${e}`).join('\n'));
  process.exit(1);
}

const order = (id) => (id === 'JD-APP' ? '0' : id.startsWith('JD-M') ? `1${id}` : `2${id}`);
modules.sort((a, b) => order(a.id).localeCompare(order(b.id)));

const rows = modules.map(
  (m) =>
    `| ${m.id} | \`${m.name}\` | \`${m.path}\` | ${m.status} | ${m.version} | ${m.description} | ${(m.consumes ?? []).join(', ') || '—'} |`,
);
const md = `# Module Registry

> GENERATED by \`pnpm modules:registry\` from \`*/module.json\` and \`docs/modules/planned.json\` — do not edit by hand.
> Module rules: [ADR-0001](../adr/0001-modular-monolith.md).

| ID | Package | Path | Status | Version | Description | Consumes |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== md) {
    console.error('docs/modules/REGISTRY.md is stale. Run: pnpm modules:registry');
    process.exit(1);
  }
  console.log(`Module registry up to date (${modules.length} modules).`);
} else {
  writeFileSync(target, md);
  console.log(`Wrote docs/modules/REGISTRY.md (${modules.length} modules).`);
}
