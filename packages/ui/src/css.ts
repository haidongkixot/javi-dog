import { font, neutrals, palette, radius, shadow, themes, type ThemeName } from './tokens.ts';

const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const HEADER = `/* GENERATED by packages/ui/scripts/generate-tokens-css.ts from src/tokens.ts — do not edit. */`;

const block = (selector: string, vars: Record<string, string>): string =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  --jd-${k}: ${v};`)
    .join('\n')}\n}`;

/** Render all themes as CSS custom properties. Light is also the `:root` default (decision D2). */
export const renderTokensCss = (): string => {
  const shared: Record<string, string> = {
    // Raw brand fills (pastels are fills only — never text on light surfaces).
    ...Object.fromEntries(Object.entries(palette).map(([k, v]) => [`brand-${kebab(k)}`, v])),
    ...Object.fromEntries(
      (['violetSoft', 'coralSoft', 'yellowSoft', 'skySoft'] as const).map((k) => [
        `brand-${kebab(k)}`,
        neutrals[k],
      ]),
    ),
    ...Object.fromEntries(Object.entries(radius).map(([k, v]) => [`radius-${k}`, v])),
    ...Object.fromEntries(Object.entries(shadow).map(([k, v]) => [`shadow-${k}`, v])),
    'font-sans': font.sans,
    'font-mono': font.mono,
  };
  const themeBlocks = (Object.keys(themes) as ThemeName[]).map((name) =>
    block(
      name === 'light' ? `:root,\n[data-theme='light']` : `[data-theme='${name}']`,
      themes[name],
    ),
  );
  return [HEADER, block(':root', shared), ...themeBlocks].join('\n\n') + '\n';
};
